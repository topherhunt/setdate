#!/bin/bash
# Publishes the current main commit as a GitHub release. Run with:
#   bash scripts/release.sh
#
# The version comes from package.json, so bump it and promote the CHANGELOG
# entry, then commit and push first. Refuses unless you're on main with a clean
# tree that matches origin/main and the version isn't already released. It never
# commits or pushes: it creates the tag on GitHub at that exact commit, which
# triggers .github/workflows/release.yml to build every platform and publish.
# Windows can't be built here: npm only installs the exiftool binary for the
# current OS, so a Windows build from macOS would ship without exiftool.
set -euo pipefail
cd "$(dirname "$0")/.."

die() { echo "!! $*" >&2; exit 1; }

[ $# -eq 0 ] || die "takes no arguments; the version comes from package.json"
VERSION="$(node -p "require('./package.json').version")"
TAG="v$VERSION"

echo "==> preflight"
command -v gh >/dev/null       || die "gh is not installed:  brew install gh"
gh auth status >/dev/null 2>&1 || die "gh is not logged in:  gh auth login"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
[ "$BRANCH" = "main" ] || die "on branch '$BRANCH'; releases are cut from main"
[ -z "$(git status --porcelain)" ] || die "uncommitted changes; commit or discard them first"
git fetch --quiet origin main
[ "$(git rev-parse HEAD)" = "$(git rev-parse origin/main)" ] \
  || die "main and origin/main differ; push (or pull) first"
[ -z "$(git ls-remote --tags origin "refs/tags/$TAG")" ] \
  || die "$TAG is already released; bump the version in package.json, commit, and push"
grep -q "^## \[$VERSION\]" CHANGELOG.md \
  || die "CHANGELOG.md has no '## [$VERSION]' entry; promote Unreleased first"
COMMIT="$(git rev-parse HEAD)"
REPO="$(gh repo view --json nameWithOwner -q .nameWithOwner)"

echo "==> testing"
npm test

cat <<SUMMARY

------------------------------------------------------------
Ready to publish $TAG
  commit   ${COMMIT:0:10} ($(git log -1 --format=%s))
  repo     $REPO
  builds   on GitHub Actions: macOS (apple-silicon, apple-intel) + Windows
  notes    generated by GitHub from commits since the last release
------------------------------------------------------------
SUMMARY

read -r -p "Publish? [y/N] " reply
[ "$reply" = "y" ] || [ "$reply" = "Y" ] || die "aborted; nothing was published"

gh api --silent "repos/$REPO/git/refs" -f ref="refs/tags/$TAG" -f sha="$COMMIT"
git fetch --quiet --tags origin

echo "==> waiting for the release workflow to start"
RUN_ID=""
for _ in $(seq 30); do
  RUN_ID="$(gh run list --workflow release.yml --branch "$TAG" --json databaseId -q '.[0].databaseId')"
  [ -n "$RUN_ID" ] && break
  sleep 2
done
[ -n "$RUN_ID" ] || die "$TAG was created but no release workflow run appeared; check https://github.com/$REPO/actions"

gh run watch "$RUN_ID" --exit-status \
  || die "release workflow failed; $TAG exists but may have no release. See: gh run view $RUN_ID --log-failed"

echo
echo "Published: $(gh release view "$TAG" --json url -q .url)"
